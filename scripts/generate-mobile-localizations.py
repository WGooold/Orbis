#!/usr/bin/env python3
"""Generate both native catalogs from one reviewed source. Use --check in CI."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'localization/mobile.json'
SWIFT = ROOT / 'ios/Orbis/Orbis/LocalizationCatalog.swift'
KOTLIN = ROOT / 'android/app/src/main/java/com/orbising/orbis/LocalizationCatalog.kt'


def unique_pairs(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f'Duplicate translation: {key!r}')
        result[key] = value
    return result


def quoted(value, kotlin=False):
    value = json.dumps(value, ensure_ascii=False)
    return value.replace('$', r'\$') if kotlin else value


def outputs():
    catalog = json.loads(SOURCE.read_text(), object_pairs_hook=unique_pairs)
    host = json.loads((SOURCE.parent / 'mobile-host.json').read_text(), object_pairs_hook=unique_pairs)
    for key, target in {**host['exact'], **host['templates']}.items():
        if key in catalog and catalog[key] != target:
            raise ValueError(f'Conflicting Host UI translation: {key!r}')
        catalog[key] = target
    for key in host['templates']:
        if re.findall(r'\{\d+\}', key) != ['{0}']:
            raise ValueError(f'Host UI templates must contain one opaque value: {key!r}')
    singular = json.loads((SOURCE.parent / 'mobile-plurals.json').read_text(), object_pairs_hook=unique_pairs)
    for key in singular:
        if key not in catalog or '{0}' not in key:
            raise ValueError(f'Plural key has no count or base translation: {key!r}')
    for source, target in [*catalog.items(), *singular.items()]:
        if not source or not isinstance(target, str) or not target:
            raise ValueError(f'Empty translation: {source!r}')
        placeholders = lambda value: sorted(re.findall(r'\{\d+\}|%\.?\d*[dfs@]', value))
        if placeholders(source) != placeholders(target):
            raise ValueError(f'Placeholder mismatch: {source!r} -> {target!r}')
    entries = sorted(catalog.items())
    swift = '// Generated by scripts/generate-mobile-localizations.py. Edit localization/mobile.json.\n'
    swift += 'enum LocalizationCatalog {\n    static let english: [String: String] = [\n'
    swift += ''.join(f'        {quoted(key)}: {quoted(value)},\n' for key, value in entries)
    swift += '    ]\n    static let singular: [String: String] = [\n'
    swift += ''.join(f'        {quoted(key)}: {quoted(value)},\n' for key, value in sorted(singular.items()))
    swift += '    ]\n    static let hostExact: Set<String> = [\n'
    swift += ''.join(f'        {quoted(key)},\n' for key in sorted(host['exact']))
    swift += '    ]\n    static let hostTemplates: [String] = [\n'
    swift += ''.join(f'        {quoted(key)},\n' for key in sorted(host['templates']))
    swift += '    ]\n}\n'
    # Keep each initializer small enough for the JVM method-size limit.
    kotlin = '// Generated by scripts/generate-mobile-localizations.py. Edit localization/mobile.json.\npackage com.orbising.orbis\n\n'
    kotlin += 'internal object LocalizationCatalog {\n    val english: Map<String, String> = buildMap {\n'
    chunks = [entries[i:i+150] for i in range(0, len(entries), 150)]
    kotlin += ''.join(f'        putAll(part{i}())\n' for i in range(len(chunks)))
    kotlin += '    }\n'
    for i, entries in enumerate(chunks):
        kotlin += f'    private fun part{i}(): Map<String, String> = mapOf(\n'
        kotlin += ''.join(f'        {quoted(key, True)} to {quoted(value, True)},\n' for key, value in entries)
        kotlin += '    )\n'
    kotlin += '    val singular: Map<String, String> = mapOf(\n'
    kotlin += ''.join(f'        {quoted(key, True)} to {quoted(value, True)},\n' for key, value in sorted(singular.items()))
    kotlin += '    )\n    val hostExact: Set<String> = setOf(\n'
    kotlin += ''.join(f'        {quoted(key, True)},\n' for key in sorted(host['exact']))
    kotlin += '    )\n    val hostTemplates: List<String> = listOf(\n'
    kotlin += ''.join(f'        {quoted(key, True)},\n' for key in sorted(host['templates']))
    kotlin += '    )\n}\n'
    for directory, suffix in [('ios/Orbis/Orbis', '*.swift'), ('android/app/src/main/java/com/orbising/orbis', '*.kt')]:
        for path in (ROOT / directory).glob(suffix):
            if path.name.startswith('LocalizationCatalog'): continue
            for match in re.finditer(r'L10n\.tr\(("(?:\\.|[^"\\])*")', path.read_text()):
                key = json.loads(match[1].replace(r'\$', '$'))
                if key not in catalog:
                    raise ValueError(f'Missing translation in {path.relative_to(ROOT)}: {key!r}')
    return {SWIFT: swift, KOTLIN: kotlin}, len(catalog)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    files, count = outputs()
    for path, content in files.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Outdated catalog: {path.relative_to(ROOT)}')
        else:
            path.write_text(content)
    print(f'{count} translations; placeholders and both native catalogs verified')
