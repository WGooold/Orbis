import { execFileSync } from "node:child_process";
import { writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { join, resolve } from "node:path";
import { rolldown } from "rolldown";
import { curatedPresets } from "./curated-presets.mjs";

// Reproducible data import for the additive native Agents; the runtime catalog has no dependency on the checkout.
const reference = resolve(process.argv[2] ?? "/Volumes/WD1TB/Projects/cc-switch");
const git = (...args) => execFileSync("git", args, { cwd: reference, encoding: "utf8" }).trim();
const commit = git("rev-parse", "HEAD");
if (!commit.startsWith("fa4a237")) throw new Error(`Expected CC Switch fa4a237; got ${commit}`);
if (git("status", "--porcelain", "--", "src/config")) throw new Error("Reference source has uncommitted changes");
const entry = ["opencode", "openclaw", "hermes", "kimi"].map(kind => `export { ${kind}ProviderPresets } from "./${kind}ProviderPresets";`).join("\n")
  + '\nexport { HERMES_BUILTIN_PROVIDER_IDS } from "./hermesBuiltinProviderIds";';
const bundle = await rolldown({
  input: "presets", platform: "node",
  plugins: [{ name: "presets", resolveId: id => id === "presets" ? join(reference, "src/config/__orbis_presets.ts") : undefined, load: id => id.endsWith("__orbis_presets.ts") ? entry : undefined }],
  resolve: { alias: { "@": join(reference, "src"), zod: createRequire(import.meta.url).resolve("zod") } },
});
const { output } = await bundle.generate({ format: "esm", codeSplitting: false });
const source = await import(`data:text/javascript;base64,${Buffer.from(output[0].code).toString("base64")}`);
const used = new Set();
function slug(kind, preset) {
  const declared = preset.providerKey ?? (kind === "hermes" ? preset.settingsConfig.name : undefined);
  const base = declared?.replace(/^cc-switch-/, "") || preset.name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || preset.icon || "custom";
  let key = base;
  for (let n = 2; used.has(`${kind}:${key}`) || (kind === "hermes" && source.HERMES_BUILTIN_PROVIDER_IDS.has(key)); n++) key = `${base}-${n}`;
  used.add(`${kind}:${key}`);
  return key;
}
const presets = [];
for (const [kind, rows] of [["opencode", source.opencodeProviderPresets], ["openclaw", source.openclawProviderPresets], ["hermes", source.hermesProviderPresets], ["kimiCode", source.kimiProviderPresets]]) {
  curatedPresets(rows.filter(row => !row.hidden && !row.isCustomTemplate)).forEach((row, index) => {
    const providerKey = slug(kind, row);
    const config = JSON.parse(JSON.stringify(row.settingsConfig));
    if (kind === "hermes") { delete config.name; config.models = Object.fromEntries((config.models ?? []).map(model => [model.id, Object.fromEntries(Object.entries(model).filter(([key]) => key !== "id" && key !== "name"))])); }
    // A preset key renamed to stay unique must carry its model keys with it.
    if (kind === "kimiCode") config.models = Object.fromEntries(Object.entries(config.models).map(([key, model]) => [`${providerKey}/${key.slice(key.indexOf("/") + 1)}`, model]));
    presets.push({ id: `${kind}-${index}`, kind, name: row.name, providerKey, category: row.category ?? (row.isOfficial ? "official" : "custom"), websiteUrl: row.websiteUrl ?? "", ...(row.icon ? { icon: row.icon } : {}), config });
  });
}
await writeFile(new URL("../packages/host/src/provider-native-presets.ts", import.meta.url),
  `// CC Switch ${commit.slice(0, 8)} preset data (MIT). Generated by scripts/import-ccswitch-native-presets.mjs.\n// See packages/windows-host/THIRD-PARTY-NOTICES.md.\nimport type { ProviderPreset } from "./provider-presets.js";\n`
  + `export const hermesBuiltinProviderIds: ReadonlySet<string> = new Set(${JSON.stringify([...source.HERMES_BUILTIN_PROVIDER_IDS])});\n`
  + `export const nativeProviderPresets: ProviderPreset[] = ${JSON.stringify(presets, null, 1)};\n`);
console.log(Object.entries(Object.groupBy(presets, row => row.kind)).map(([kind, rows]) => `${kind} ${rows.length}`).join(", "));
