export async function createPortal({ hostService, publicRelayUrl, port = 8788, host = "0.0.0.0", ready = () => true }) {
  let opening = false;
  const server = createServer(async (req, res) => {
    res.setHeader("Cache-Control", "no-store");
    res.setHeader("X-Content-Type-Options", "nosniff");
    res.setHeader("Referrer-Policy", "no-referrer");
    res.setHeader("X-Robots-Tag", "noindex, nofollow");
    res.setHeader("Content-Security-Policy", `default-src 'none'; script-src 'sha256-${cspHash}'; style-src 'unsafe-inline'; img-src data:; connect-src 'self'; frame-ancestors 'none'; base-uri 'none'; form-action 'none'`);
    if (req.url === "/healthz" && req.method === "GET") return json(res, ready() ? 200 : 503, { ok: ready() });
    if (req.url === "/" && req.method === "GET") {
      res.writeHead(200, { "content-type": "text/html; charset=utf-8" }); return res.end(page);
    }
    if (req.url !== "/pair" || req.method !== "POST") return json(res, 404, { error: "Not found" });
    if (req.headers["x-review-request"] !== "1") return json(res, 403, { error: "Open the review page to generate a code" });
    if (!ready()) return json(res, 503, { error: "Review Host is reconnecting. Try again shortly." });
    if (opening) return json(res, 409, { error: "A pairing code is being prepared. Try again shortly." });
    opening = true;
    try {
      const window = await hostService.openPairingWindow({ ttlSeconds: 120, lan: [] });
      const text = encodePairingQrText({ ...window.payload, relayUrl: publicRelayUrl });
      const image = await QRCode.toDataURL(text, { width: 600, margin: 2 });
      json(res, 200, { text, image, expiresAt: window.expiresAtMs });
    } catch { json(res, 503, { error: "Could not create a pairing code. Try again shortly." }); }
    finally { opening = false; }
  });
  await new Promise((resolve, reject) => { server.once("error", reject); server.listen(port, host, resolve); });
  return { server, url: `http://127.0.0.1:${server.address().port}`, close: () => new Promise(resolve => server.close(resolve)) };
}
