import { readFile, writeFile } from "node:fs/promises";
import { resolve, join } from "node:path";
import { execFileSync } from "node:child_process";
import ts from "typescript";

const reference = resolve(process.argv[2] ?? "../cc-switch");
const commit = "4ed071500b07ba5801be84c96ddb4e03bdf48a2d";
if (execFileSync("git", ["rev-parse", "HEAD"], { cwd: reference, encoding: "utf8" }).trim() !== commit) throw new Error(`Expected CC Switch ${commit}`);
if (execFileSync("git", ["status", "--porcelain", "--", "src/config/claudeProviderPresets.ts"], { cwd: reference, encoding: "utf8" }).trim()) throw new Error("Reference preset source has uncommitted changes");
const source = await readFile(join(reference, "src/config/claudeProviderPresets.ts"), "utf8");
const js = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ES2022 } }).outputText;
const { providerPresets } = await import(`data:text/javascript;base64,${Buffer.from(js).toString("base64")}`);
// Native Claude switching supports Messages endpoints; proxy/OAuth conversion presets require a different runtime.
const presets = providerPresets.flatMap((p, index) => p.hidden || p.requiresOAuth || p.apiFormat && p.apiFormat !== "anthropic" ? [] : [{
  id: `claude-${index}`, kind: "claude", name: p.name, category: p.isOfficial ? "official" : p.category ?? "custom",
  websiteUrl: p.websiteUrl, config: p.settingsConfig,
}]);
await writeFile(new URL("../packages/host/src/claude-provider-presets.ts", import.meta.url),
  `// CC Switch ${commit} (MIT). Generated by scripts/import-claude-presets.mjs.\n// See packages/windows-host/THIRD-PARTY-NOTICES.md.\nimport type { ProviderPreset } from "./provider-presets.js";\nexport const claudeProviderPresets: ProviderPreset[] = ${JSON.stringify(presets, null, 2)};\n`);
console.log(`Imported ${presets.length} native Claude presets`);
