/**
 * 终端里的 `pi` 命令：只为 **Orbis Host 自己安装的 Pi** 提供。
 *
 * Host 把每个 Pi 版本装进独立的带 id 目录（便于升级与回滚），它们都不在 PATH 上。用户自己装的 Pi
 * 本来就有 `pi` 命令，这里绝不生成第二个、也绝不覆盖它（PATH 上出现任何别人的 `pi` 都让位）。
 *
 * 命令本身不写死版本：每次运行都读 Host 的安装记录取当前激活的那份，所以 Pi 升级、切换版本之后
 * 不需要重新生成。它也不依赖用户装了 node：用 Host 自带的 node 运行，找不到时才退回 PATH 上的 node。
 *
 * - macOS：脚本放在用户可写的 `~/Library/Application Support/Orbis/bin/pi`，`/usr/local/bin/pi` 只是
 *   指向它的符号链接。`/usr/local/bin` 在 `/etc/paths` 里，zsh、bash、fish、各种终端和 ssh 都能找到；
 *   它通常属于 root，所以创建链接要一次管理员授权（与 VS Code 的「安装 code 命令」相同）。之后 Host
 *   被移动只需重写用户目录里的脚本，不再需要授权。
 * - Windows：`%LOCALAPPDATA%\Orbis\bin\pi.cmd`，与 `codex.cmd` 共用用户 PATH 上的同一项，不需要提权。
 */
import { execFile } from "node:child_process";
import { constants } from "node:fs";
import { access, lstat, mkdir, readFile, readlink, realpath, rm, symlink, writeFile } from "node:fs/promises";
import { homedir } from "node:os";
import { delimiter, dirname, join, resolve, win32 } from "node:path";
import { promisify } from "node:util";

import { ensureOrbisBinOnUserPath, orbisBinDirectory } from "./codex-shim-install.js";

const execute = promisify(execFile);

/** 生成文件里的标记：判断「这是我们的」只认它，绝不按名字猜。 */
export const PI_COMMAND_MARK = "orbis-pi-command";
export const MAC_PI_LINK = "/usr/local/bin/pi";

/** 用户在授权框里点了取消：调用方据此记住选择，不再主动弹出。 */
export class PiCommandCancelledError extends Error {
  constructor() { super("已取消管理员授权，pi 命令未改动"); this.name = "PiCommandCancelledError"; }
}

export type PiCommandState = "installed" | "available" | "foreign" | "unavailable";
export type PiCommandStatus = { state: PiCommandState; detail: string; path?: string };

export function piCommandScriptPath(platform: NodeJS.Platform = process.platform, home = homedir()): string {
  return platform === "win32" ? join(orbisBinDirectory(), "pi.cmd") : join(home, "Library", "Application Support", "Orbis", "bin", "pi");
}

function shellQuote(value: string): string {
  return `'${value.replaceAll("'", `'\\''`)}'`;
}

/** 读安装记录、取当前激活入口的那段 JS；macOS 脚本与 Windows 的 pi-shim 用同一套规则。 */
const ACTIVE_ENTRY_JS = "const fs=require('fs');try{const d=JSON.parse(fs.readFileSync(process.argv[1],'utf8'));const a=(d.installations||[]).find(i=>i&&i.active);if(a&&typeof a.entry==='string'&&fs.existsSync(a.entry))process.stdout.write(a.entry)}catch{}";

export function renderMacPiCommand(node: string, managedRoot: string): string {
  return [
    "#!/bin/sh",
    `# ${PI_COMMAND_MARK}: 由 Orbis Host 生成，运行 Orbis Host 安装的 Pi。可在 Orbis Host 设置中移除。`,
    `manifest=${shellQuote(join(managedRoot, "pi", "installations.json"))}`,
    `node=${shellQuote(node)}`,
    "if [ ! -x \"$node\" ]; then node=$(command -v node 2>/dev/null || true); fi",
    "if [ -z \"$node\" ]; then",
    "  echo \"pi: 找不到 Orbis Host 自带的 node（Orbis Host 可能已被移动或删除）。请重新打开 Orbis Host，或在它的设置里移除 pi 命令。\" >&2",
    "  exit 127",
    "fi",
    `entry=$("$node" -e ${shellQuote(ACTIVE_ENTRY_JS)} "$manifest")`,
    "if [ -z \"$entry\" ]; then",
    "  echo \"pi: Orbis Host 里没有可用的 Pi。请在 Orbis Host 的 Agent 页安装 Pi，或在它的设置里移除 pi 命令。\" >&2",
    "  exit 127",
    "fi",
    "exec \"$node\" \"$entry\" \"$@\"",
    "",
  ].join("\n");
}

export function renderWindowsPiCommand(runtimeRoot: string, managedRoot: string): string {
  const runtime = win32.resolve(runtimeRoot).replace(/"/gu, "");
  return [
    "@echo off",
    `rem ${PI_COMMAND_MARK}: generated by Orbis Host for the Pi it installed`,
    "setlocal",
    `set "ORBIS_PI_COMMAND_ROOT=${win32.resolve(managedRoot).replace(/"/gu, "")}"`,
    `"${runtime}\\node\\node.exe" "${runtime}\\packages\\host\\dist\\pi-shim.js" %*`,
    "exit /b %errorlevel%",
    "",
  ].join("\r\n");
}

async function isOurs(path: string): Promise<boolean> {
  return (await readFile(path, "utf8").catch(() => "")).includes(PI_COMMAND_MARK);
}

async function executable(path: string): Promise<boolean> {
  try { await access(path, constants.X_OK); return (await lstat(path)).isFile() || (await lstat(path)).isSymbolicLink(); }
  catch { return false; }
}

/**
 * PATH 上第一个不是我们的 `pi`。它存在就说明用户自己有 Pi（npm、Homebrew、独立二进制……），
 * Orbis 的命令必须让位。
 */
export async function findForeignPi(env: NodeJS.ProcessEnv, platform: NodeJS.Platform = process.platform): Promise<string | undefined> {
  const names = platform === "win32" ? ["pi.exe", "pi.cmd", "pi.bat", "pi.ps1", "pi.com"] : ["pi"];
  const ours = new Set<string>();
  for (const path of [piCommandScriptPath(platform), ...(platform === "darwin" ? [MAC_PI_LINK] : [])]) {
    try { ours.add((await realpath(path)).toLowerCase()); } catch { /* 不存在 */ }
  }
  for (const dir of (env.PATH ?? env.Path ?? "").split(platform === "win32" ? ";" : delimiter).map(item => item.trim().replace(/^"|"$/g, "")).filter(Boolean)) {
    for (const name of names) {
      const candidate = join(dir, name);
      if (!await executable(candidate) && !(platform === "win32" && await access(candidate).then(() => true, () => false))) continue;
      let actual: string;
      try { actual = (await realpath(candidate)).toLowerCase(); } catch { continue; }
      if (ours.has(actual) || await isOurs(candidate)) continue;
      return candidate;
    }
  }
  return undefined;
}

async function macLinkIsOurs(script: string): Promise<boolean> {
  try { return (await lstat(MAC_PI_LINK)).isSymbolicLink() && resolve(dirname(MAC_PI_LINK), await readlink(MAC_PI_LINK)) === script; }
  catch { return false; }
}

export type PiCommandContext = {
  platform?: NodeJS.Platform;
  env?: NodeJS.ProcessEnv;
  /** Host 当前激活的托管 Pi；没有就无从提供命令。 */
  managedEntry: string | undefined;
  /** Host 正在使用的 Pi 是否就是托管的那份（用户自己的 Pi 优先时它不是）。 */
  usingManaged: boolean;
};

export async function piCommandStatus(context: PiCommandContext): Promise<PiCommandStatus> {
  const platform = context.platform ?? process.platform;
  if (platform !== "darwin" && platform !== "win32") return { state: "unavailable", detail: "此平台不提供 pi 命令" };
  const script = piCommandScriptPath(platform);
  const installed = platform === "darwin" ? await macLinkIsOurs(script) && await isOurs(script) : await isOurs(script);
  const foreign = await findForeignPi(context.env ?? process.env, platform);
  if (foreign !== undefined) return { state: "foreign", path: foreign, detail: `终端里的 pi 来自 ${foreign}，Orbis 不会改动它` };
  if (installed) return { state: "installed", path: platform === "darwin" ? MAC_PI_LINK : script, detail: "终端里可以直接运行 pi（新开的终端窗口生效）" };
  if (context.managedEntry === undefined || !context.usingManaged) return { state: "unavailable", detail: "没有由 Orbis 安装的 Pi" };
  return { state: "available", detail: platform === "darwin" ? "Orbis 安装的 Pi 还不能在终端里直接运行；安装 pi 命令需要一次管理员授权" : "Orbis 安装的 Pi 还没有终端命令" };
}

/** 只写用户目录里的脚本（内容一致就不动）。返回脚本路径。 */
async function writeScript(platform: NodeJS.Platform, content: string): Promise<string> {
  const script = piCommandScriptPath(platform);
  const existing = await readFile(script, "utf8").catch(() => undefined);
  if (existing !== undefined && !existing.includes(PI_COMMAND_MARK)) throw new Error(`${script} 已存在且不是 Orbis 生成的，未覆盖`);
  if (existing !== content) {
    await mkdir(dirname(script), { recursive: true });
    await writeFile(script, content, { mode: platform === "win32" ? 0o644 : 0o755 });
  }
  return script;
}

async function administrator(script: string, argument: string): Promise<void> {
  // 参数经 argv 传给 AppleScript，再用 `quoted form of` 交给 shell：路径里的引号、空格都不会变成命令。
  try {
    await execute("/usr/bin/osascript", ["-e", "on run argv", "-e", `do shell script (${script}) with administrator privileges`, "-e", "end run", argument], { timeout: 120_000 });
  } catch (error) {
    const stderr = String((error as { stderr?: unknown }).stderr ?? "");
    if (stderr.includes("-128")) throw new PiCommandCancelledError();
    throw new Error(`需要管理员授权才能修改 ${MAC_PI_LINK}：${stderr.trim() || (error instanceof Error ? error.message : String(error))}`);
  }
}

/** macOS：生成脚本并创建 `/usr/local/bin/pi` 链接（目录不可写时请求一次管理员授权）。 */
export async function installMacPiCommand(node: string, managedRoot: string, env: NodeJS.ProcessEnv = process.env): Promise<void> {
  const foreign = await findForeignPi(env, "darwin");
  if (foreign !== undefined) throw new Error(`终端里已经有 pi（${foreign}），Orbis 不会覆盖它`);
  const script = await writeScript("darwin", renderMacPiCommand(node, managedRoot));
  if (await macLinkIsOurs(script)) return;
  if (await lstat(MAC_PI_LINK).then(() => true, () => false)) throw new Error(`${MAC_PI_LINK} 已存在且不是 Orbis 的，未覆盖`);
  try {
    await symlink(script, MAC_PI_LINK);
  } catch (error) {
    const code = (error as { code?: unknown }).code;
    if (code !== "EACCES" && code !== "EPERM" && code !== "ENOENT") throw error;
    await administrator(`"/bin/mkdir -p /usr/local/bin && /bin/ln -s " & quoted form of (item 1 of argv) & " ${MAC_PI_LINK}"`, script);
  }
}

/** macOS：只移除指向我们脚本的那个链接，再删脚本。 */
export async function removeMacPiCommand(): Promise<void> {
  const script = piCommandScriptPath("darwin");
  if (await macLinkIsOurs(script)) {
    try { await rm(MAC_PI_LINK); }
    catch (error) {
      const code = (error as { code?: unknown }).code;
      if (code !== "EACCES" && code !== "EPERM") throw error;
      await administrator(`"[ \\"$(/usr/bin/readlink ${MAC_PI_LINK})\\" = " & quoted form of (item 1 of argv) & " ] && /bin/rm -f ${MAC_PI_LINK}; true"`, script);
    }
  }
  if (await isOurs(script)) await rm(script, { force: true });
}

/** macOS：Host 启动时让已安装的命令跟上 Host 当前的位置；没装过就什么都不做。 */
export async function refreshMacPiCommand(node: string, managedRoot: string): Promise<void> {
  const script = piCommandScriptPath("darwin");
  if (await isOurs(script)) await writeScript("darwin", renderMacPiCommand(node, managedRoot));
}

/**
 * Windows：自动维护。Host 用的是自己安装的 Pi 且 PATH 上没有别人的 `pi` 时生成 `pi.cmd`；
 * 否则移除我们的那份（用户后来自己装了 Pi，就让位给它）。
 */
export async function syncWindowsPiCommand(context: PiCommandContext & { runtimeRoot: string; managedRoot: string }): Promise<void> {
  const script = piCommandScriptPath("win32");
  const foreign = await findForeignPi(context.env ?? process.env, "win32");
  if (foreign === undefined && context.managedEntry !== undefined && context.usingManaged) {
    await writeScript("win32", renderWindowsPiCommand(context.runtimeRoot, context.managedRoot));
    await ensureOrbisBinOnUserPath();
  } else if (await isOurs(script)) {
    await rm(script, { force: true });
  }
}
